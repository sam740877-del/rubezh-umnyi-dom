"""Сторож слоёв: логика учёта не знает про веб.

Зачем этот файл существует
--------------------------

Решение владельца 06.09.2026: систему делаем браузерной, но оставляем
возможность позже надеть на ту же логику настольный интерфейс на Qt,
как у остальной семьи («Электро», «Заявки», БПО, ТБ). Возможность эта
держится на одном условии — правила учёта не должны знать, через что
их вызвали.

Условие соблюдается ровно до первой строчки вроде
`raise HTTPException(...)` в `services.py`, написанной в спешке. Такая
строчка ничего не ломает сегодня и стоит переписанного слоя завтра.
Разошедшийся слой замечают не в момент разлома, а в момент переезда,
когда поздно.

Почему разбор импортов, а не поиск строк
-----------------------------------------

Свод БПО (`guard_budget.py`) держит потолок текстовых сторожей на нуле:
из семи сторожей, читавших исходник глазами, шесть покраснели на
исправном продукте — они искали строки, а строки законно переезжают.

Здесь предмет охраны другой: не текст, а факт зависимости модуля от
чужого слоя. Он читается из дерева разбора (`ast`) — переименование
переменной или перенос функции такой сторож не обманет.

Граница честности
------------------

Сторож видит импорты, а не намерения. Вызвать веб через
`importlib.import_module("fastapi")` он не поймает. Это цена простоты:
случайную оплошность он ловит, обход в обход правила — нет. От обхода
защищает не сторож, а понимание, зачем правило.
"""

from __future__ import annotations

import ast
from pathlib import Path

APP = Path(__file__).resolve().parent.parent / "app"

#: Слой логики: эти модули переживут смену интерфейса и переедут в Qt
#: как есть. Всё, что решает «можно или нельзя», живёт здесь.
CORE_MODULES = (
    "models.py",
    "services.py",
    "database.py",
    "seed.py",
    "audit.py",
    "security.py",
    "attachments.py",
    "notifications.py",
    "backup.py",
)

#: Пакеты интерфейса. Слой логики не имеет права о них знать.
#: Список открытый: добавится Qt — добавится и сюда, чтобы правило
#: работало в обе стороны и логика не приросла уже к настольному виду.
WEB_PACKAGES = {
    "fastapi",
    "starlette",
    "jinja2",
    "uvicorn",
    "httpx",
    "multipart",
    "PySide6",
    "shiboken6",
}


def _imported_roots(path: Path) -> set[str]:
    """Корневые имена пакетов, от которых зависит модуль.

    Берём именно корень (`fastapi.responses` → `fastapi`): запрет
    касается всего пакета, а перечислять его подмодули — заведомо
    отстающий от жизни список.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    roots: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                roots.add(alias.name.split(".")[0])
        elif isinstance(node, ast.ImportFrom):
            # Относительный импорт (level > 0) ведёт внутрь app — это свои.
            if node.level == 0 and node.module:
                roots.add(node.module.split(".")[0])
    return roots


def test_core_does_not_import_web() -> None:
    """Правила учёта не зависят от интерфейса — иначе переезд на Qt
    означает переписать их заново, а не перенести файлом."""
    offenders: list[str] = []
    for name in CORE_MODULES:
        path = APP / name
        assert path.exists(), f"Модуль слоя логики пропал: {name}"
        for root in sorted(_imported_roots(path) & WEB_PACKAGES):
            offenders.append(f"{name} → {root}")

    assert not offenders, (
        "Слой логики знает про интерфейс: "
        + ", ".join(offenders)
        + ". Правила учёта должны решать «можно или нельзя» сами, "
        "не поднимая веб-ошибок и не зная про шаблоны. "
        "Проверку прав и текст ответа переносите в app/main.py."
    )


def test_core_modules_are_covered() -> None:
    """Новый модуль логики должен попадать под сторожа сам.

    Без этой проверки правило тихо перестаёт работать: кто-то заводит
    `app/rules.py`, сторож о нём не знает и остаётся зелёным навсегда.
    """
    # session_cookie.py — механизм веба (печенье сеанса), при переезде на Qt
    # он выбрасывается вместе с main.py, поэтому стоит рядом с ним, а не
    # в слое логики.
    known = set(CORE_MODULES) | {"main.py", "session_cookie.py", "__init__.py"}
    found = {p.name for p in APP.glob("*.py")}
    unknown = sorted(found - known)

    assert not unknown, (
        "В app/ появились модули, о которых сторож слоёв не знает: "
        + ", ".join(unknown)
        + ". Отнесите каждый к слою: логика — в CORE_MODULES этого файла, "
        "интерфейс — в белый список known здесь же."
    )
